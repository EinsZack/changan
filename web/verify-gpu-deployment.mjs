import {chromium} from 'playwright';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1536,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8310/');
await page.getByRole('button',{name:'执行节点',exact:true}).click();
await page.getByRole('heading',{name:'gpu-1',exact:true}).waitFor();
await page.screenshot({path:'../docs/gpu-20261108/production-nodes.png',fullPage:true});
await page.getByRole('button',{name:'任务中心',exact:false}).first().click();
await page.getByText('0.6.0正式验证 · CUDA',{exact:true}).click();
await page.getByRole('button',{name:'容器与镜像',exact:true}).click();
await page.locator('.session-table').getByText('NVIDIA GPU / CUDA',{exact:true}).waitFor();
await page.screenshot({path:'../docs/gpu-20261108/production-session.png',fullPage:true});
await page.getByRole('button',{name:'任务中心',exact:false}).first().click();
await page.getByRole('button',{name:'新建分析任务'}).click();
await page.waitForFunction(()=>document.querySelector('[aria-label="推理后端"]')?.value==='cuda');
await page.screenshot({path:'../docs/gpu-20261108/production-new-task.png',fullPage:true});
await page.getByRole('button',{name:'取消',exact:true}).click();
fs.writeFileSync('../docs/gpu-20261108/production-browser.json',JSON.stringify({errors,default_backend:'cuda',actual_provider_visible:true,at:new Date().toISOString()},null,2));
if(errors.length)throw new Error(errors.join('\n'));await browser.close();
