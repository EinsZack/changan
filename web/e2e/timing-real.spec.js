import {test,expect} from '@playwright/test';
import fs from 'node:fs';
test('real GPU timing, CPU comparison and mobile',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const report=JSON.parse(fs.readFileSync('../docs/gpu-timing-20261110/benchmark.json','utf8'));
 const gpu=report.runs.find(r=>r.policy==='auto'&&r.nodes.length===1);
 const cpu=report.runs.find(r=>r.policy==='cpu');
 expect(gpu).toBeTruthy();expect(cpu).toBeTruthy();
 await page.goto('/?page=detail&task='+gpu.task_id);
 const panel=page.getByRole('region',{name:'启动与推理分段计时'});
 await expect(panel).toContainText('GPU / CUDA');
 await expect(panel.locator('.timing-segments details')).toHaveCount(24);
 await panel.getByText('启动阶段明细与设备',{exact:true}).click();
 await expect(panel).toContainText('NVIDIA GeForce RTX 5090');
 await expect(panel).toContainText('CUDA 预热计算事件：203');
 await panel.locator('.timing-segments summary').first().click();
 await expect(panel.locator('.timing-segments details[open] .timing-forward')).toHaveCount(10);
 await page.screenshot({path:'../docs/gpu-timing-20261110/real-gpu-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.screenshot({path:'../docs/gpu-timing-20261110/real-gpu-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:'历史与对比',exact:true}).click();
 await page.getByLabel('基线运行').selectOption(cpu.task_id);
 await page.getByLabel('对比运行').selectOption(gpu.task_id);
 const comparison=page.getByRole('table',{name:'启动与推理对比'});
 await expect(comparison).toContainText('CPU');
 await expect(comparison).toContainText('GPU / CUDA');
 await expect(comparison).toContainText(cpu.forward_ms_per_frame.toFixed(3)+' ms');
 await expect(comparison).toContainText(gpu.forward_ms_per_frame.toFixed(3)+' ms');
 await page.screenshot({path:'../docs/gpu-timing-20261110/real-comparison.png',fullPage:true});
 expect(errors).toEqual([]);
});
