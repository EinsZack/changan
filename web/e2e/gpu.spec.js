import {test,expect} from '@playwright/test';
import fs from 'node:fs';
test('real GPU resources, selection, 24 segments in one session and runtime evidence',async({page,request})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const folder='../docs/gpu-20261108';fs.mkdirSync(folder,{recursive:true});
 await page.goto('/');
 await page.getByRole('button',{name:'执行节点',exact:true}).click();
 const gpu=page.locator('.node-card').filter({has:page.getByRole('heading',{name:'gpu-1',exact:true})});
 await expect(gpu).toContainText('RTX 5090');await expect(gpu).toContainText('已通过接入验证');
 await page.screenshot({path:folder+'/gpu-nodes.png',fullPage:true});
 await page.getByRole('button',{name:'候选节点筛选',exact:true}).click();
 await page.getByLabel('推理后端',{exact:true}).selectOption('cuda');
 await page.getByRole('button',{name:'筛选候选节点',exact:true}).click();
 await expect(page.getByText('1 / 5 个节点满足要求')).toBeVisible();
 await page.getByLabel('最低空闲显存',{exact:true}).fill('131072');
 await page.getByRole('button',{name:'筛选候选节点',exact:true}).click();
 await expect(page.getByText('0 / 5 个节点满足要求')).toBeVisible();
 await expect(page.getByText('可用显存不足或未知',{exact:false}).first()).toBeVisible();
 await page.screenshot({path:folder+'/gpu-candidates.png',fullPage:true});
 await page.getByRole('button',{name:'任务中心',exact:false}).first().click();
 await page.getByRole('button',{name:'新建分析任务'}).click();
 await expect(page.getByLabel('推理后端',{exact:true})).toHaveValue('cuda');
 await page.getByLabel('任务名称',{exact:true}).fill('GPU浏览器验收 · 24分片复用');
 await page.getByLabel('分片时长（秒）',{exact:true}).fill('1');
 await page.getByRole('button',{name:'创建并运行'}).click();
 await expect(page.locator('.task-summary').getByText('已完成',{exact:true})).toBeVisible({timeout:180000});
 await page.getByRole('button',{name:'容器与镜像',exact:true}).click();
 await expect(page.locator('.session-table tbody tr')).toHaveCount(1);
 await expect(page.locator('.session-summary')).toContainText('模型加载 1 次');
 await expect(page.locator('.session-summary')).toContainText('已完成分片 24');
 await expect(page.locator('.session-summary')).toContainText('已回收 1 / 1',{timeout:30000});
 await expect(page.locator('.session-table')).toContainText('CUDAExecutionProvider');
 await expect(page.locator('.session-table')).toContainText('实际 CUDA 计算事件：');
 await page.screenshot({path:folder+'/gpu-session.png',fullPage:true});
 await page.getByRole('button',{name:'传输与吞吐',exact:true}).click();
 await expect(page.locator('.measurement-cards')).toContainText('24 / 24');
 await page.screenshot({path:folder+'/gpu-transfer.png',fullPage:true});
 await page.getByRole('button',{name:'分析结果',exact:true}).click();
 await expect(page.locator('.preview-grid img').first()).toBeVisible();
 expect(await page.locator('.preview-grid img').first().evaluate(i=>i.complete&&i.naturalWidth>0)).toBe(true);
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'下载结果及追溯记录'}).click()]);
 await download.saveAs(folder+'/ui-task.json');
 const task=JSON.parse(fs.readFileSync(folder+'/ui-task.json','utf8'));
 expect(new Set(task.attempts.map(a=>a.execution_id)).size).toBe(1);
 expect(task.segments.every(s=>s.result.inference.provider==='CUDAExecutionProvider')).toBe(true);
 expect(errors).toEqual([]);
});
