import {test, expect} from '@playwright/test';
import fs from 'node:fs';

test('task timeout creates a persistent in-app warning with read and acknowledgement actions', async ({page, request}) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/');
    await page.getByRole('button', {name: '新建分析任务'}).click();
    await page.getByLabel('任务名称', {exact: true}).fill('站内告警验证 · 超时');
    await page.getByLabel('任务截止时限（秒）').fill('10');
    await page.getByRole('button', {name: '创建并运行'}).click();
    await expect(page.locator('.task-summary').getByText('超时', {exact: true})).toBeVisible({timeout: 30000});
    await expect(page.locator('.alert-banner')).toContainText('1 条未读告警');
    await page.getByRole('button', {name: '查看告警', exact: true}).click();
    await expect(page.getByRole('heading', {name: '站内告警', exact: true})).toBeVisible();
    const card = page.locator('.alert-card');
    await expect(card).toHaveCount(1);
    await expect(card).toContainText('任务截止时限已到');
    await expect(card).toContainText('0 / 6');
    fs.mkdirSync('../docs/screenshots', {recursive: true});
    await page.screenshot({path: '../docs/screenshots/alerts-desktop.png', fullPage: true});
    await page.getByRole('button', {name: '刷新告警'}).click();
    await expect(card).toHaveCount(1);
    await card.getByRole('button', {name: '标为已读'}).click();
    await expect.poll(async () => (await (await request.get('/api/alerts')).json()).summary.unread).toBe(0);
    await page.reload();
    await page.getByRole('button', {name: '站内告警，0条未读', exact: true}).click();
    await expect(card).toHaveCount(1);
    await expect(card.locator('.alert-unread')).toHaveCount(0);
    await card.getByRole('button', {name: '确认告警'}).click();
    await expect(page.getByRole('heading', {name: '当前筛选下没有告警'})).toBeVisible();
    await page.getByLabel('处理状态', {exact: true}).selectOption('acknowledged');
    await expect(card).toHaveCount(1);
    await page.setViewportSize({width: 390, height: 844});
    await expect(card).toBeVisible();
    await page.screenshot({path: '../docs/screenshots/alerts-mobile.png', fullPage: true});
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
    await card.getByRole('button', {name: '查看任务', exact: true}).click();
    await expect(page.getByRole('heading', {name: '站内告警验证 · 超时', exact: true})).toBeVisible();
    await expect(page.locator('.task-summary').getByText('超时', {exact: true})).toBeVisible();
    expect(errors).toEqual([]);
});

test('final preparation failure alerts while user cancellation remains quiet', async ({page, request}) => {
    const canceled = await (await request.post('/api/tasks', {data: {name: '告警验证 · 主动取消', deadline_seconds: 60}})).json();
    await request.post('/api/tasks/' + canceled.id + '/cancel');
    const failed = await (await request.post('/api/tasks', {data: {name: '告警验证 · 损坏输入', source: 'upload_alerttest'}})).json();
    await expect.poll(async () => (await (await request.get('/api/tasks/' + failed.id)).json()).status).toBe('FAILED');
    const alerts = await (await request.get('/api/alerts', {params: {task_id: failed.id}})).json();
    expect(alerts.items).toHaveLength(1);
    expect(alerts.items[0].rule).toBe('task_failed');
    expect((await (await request.get('/api/alerts', {params: {task_id: canceled.id}})).json()).total).toBe(0);
    await page.goto('/');
    await page.getByRole('button', {name: /站内告警，/}).click();
    await page.getByLabel('告警类型', {exact: true}).selectOption('task_failed');
    await expect(page.locator('.alert-card')).toHaveCount(1);
    await expect(page.locator('.alert-card')).toContainText('告警验证 · 损坏输入');
    await expect(page.locator('.alert-card')).toContainText('无法读取视频');
});
