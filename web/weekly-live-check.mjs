import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
const base='http://127.0.0.1:18410';
const out='../tmp/weekly-20261104/evidence';
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1500,height:1050},deviceScaleFactor:2,timezoneId:'Asia/Shanghai'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const request=context.request;
const get=async p=>(await request.get(base+p)).json();
const save=(name,data)=>fs.writeFileSync(out+'/'+name,JSON.stringify(data,null,2));
const waitFor=async(fn,seconds=120)=>{const end=Date.now()+seconds*1000;while(Date.now()<end){const r=await fn();if(r)return r;await new Promise(r=>setTimeout(r,500));}throw Error('Timed out');};
const shot=async(name,loc)=>{await page.evaluate(()=>document.fonts.ready);await (loc||page.locator('.content')).screenshot({path:out+'/'+name+'.png'});};
await waitFor(async()=>{const n=await get('/api/nodes');return n.every(n=>n.online&&n.snapshot.healthy);});
await page.goto(base+'/?page=candidates');
await expect(page.locator('.weekly')).toContainText('4 / 4 个节点满足要求');
await shot('25-候选筛选',page.locator('.weekly'));
const candidateNormal=await (await request.post(base+'/api/scheduling/candidates',{data:{params:{required_tags:['cpu','onnx']}}})).json();
save('25-候选筛选.json',candidateNormal);
await page.getByLabel('必要标签',{exact:true}).fill('gpu');
await page.getByRole('button',{name:'筛选候选节点',exact:true}).click();
await expect(page.locator('.weekly')).toContainText('0 / 4 个节点满足要求');
await expect(page.locator('tbody')).toContainText('缺少必要标签');
await shot('25-标签排除',page.locator('.weekly'));
const absent=await (await request.post(base+'/api/scheduling/candidates',{data:{params:{required_tags:['gpu']}}})).json();
save('25-标签排除.json',absent);
console.log('candidate filtering passed');

await page.goto(base+'/?page=tasks');
await page.getByRole('button',{name:'新建分析任务',exact:true}).click();
await page.locator('input[type=file]').setInputFiles('../assets/samples/demo.mp4');
await expect(page.getByText('已上传并校验视频元信息')).toBeVisible();
await page.getByLabel('任务名称',{exact:true}).fill('11月4日 上传视频与分片验证');
await page.getByLabel('分片时长（秒）',{exact:true}).fill('7');
await expect.poll(()=>page.locator('video').evaluate(v=>v.readyState)).toBeGreaterThan(0);
await page.locator('video').evaluate(async v=>{v.muted=true;await v.play()});
await expect.poll(()=>page.locator('video').evaluate(v=>v.currentTime)).toBeGreaterThan(0);
await page.locator('video').evaluate(v=>v.pause());
await shot('28-上传与回放',page.locator('form.modal'));
const submit=page.locator('form.modal button').filter({hasText:/创建并|提交|开始分析/});
console.log('submit buttons',await page.locator('form.modal button').allTextContents());
await page.locator('form.modal').evaluate(f=>f.requestSubmit());
await expect(page.getByRole('heading',{name:'11月4日 上传视频与分片验证',exact:true})).toBeVisible();
let normal=await waitFor(async()=>{const rows=await get('/api/tasks');const t=rows.find(t=>t.name==='11月4日 上传视频与分片验证');if(!t)return null;const d=await get('/api/tasks/'+t.id);if(['FAILED','TIMED_OUT'].includes(d.status))throw Error(d.error);return d.status==='SUCCEEDED'?d:null;});
const events=await get('/api/tasks/'+normal.id+'/events');
const reqs=events.filter(e=>e.type==='dispatch_request'),acks=events.filter(e=>e.type==='dispatch_ack');
expect(normal.segments.map(s=>s.end-s.start)).toEqual([7,7,7,3]);
expect(reqs.length).toBe(4);expect(acks.length).toBe(4);expect(acks.every(a=>a.payload.identity_matched)).toBe(true);
expect(normal.result.sampled_frames).toBe(48);
save('正常任务.json',{...normal,events});
await page.goto(base+'/?page=detail&task='+normal.id+'&tab=dispatch');
await expect(page.getByRole('heading',{name:'任务下发请求与确认回传'})).toBeVisible();
await shot('26-下发确认',page.locator('section.weekly'));
await page.getByText('下发输入与确认输出字段',{exact:true}).click();
await shot('26-输入输出字段',page.locator('section.weekly details'));
await page.goto(base+'/?page=detail&task='+normal.id+'&tab=video');
await expect(page.getByRole('heading',{name:'已生成 4 个视频片段'})).toBeVisible();
await page.getByRole('button',{name:'播放片段 4',exact:true}).click();
await expect.poll(()=>page.locator('.weekly-videos video').nth(1).evaluate(v=>v.duration)).toBe(3);
await page.locator('.weekly-videos video').evaluateAll(vs=>Promise.all(vs.map(async v=>{v.muted=true;await v.play()})));
await expect.poll(()=>page.locator('.weekly-videos video').nth(1).evaluate(v=>v.currentTime)).toBeGreaterThan(0);
await page.locator('.weekly-videos video').evaluateAll(vs=>vs.forEach(v=>v.pause()));
await shot('28-视频及尾片',page.locator('.weekly'));
await page.goto(base+'/?page=detail&task='+normal.id+'&tab=flow');
await expect(page.getByRole('heading',{name:'片段与执行落点'})).toBeVisible();
await shot('26-执行落点',page.locator('.content > section').last());
console.log('upload playback splitting dispatch passed',normal.id);

const pids=JSON.parse(fs.readFileSync('../tmp/weekly-20261104/pids.json'));
let paused=false;
try{
 const created=await (await request.post(base+'/api/tasks',{data:{name:'11月4日 受控失联验证',source:'demo',node_ids:['lab-1'],segment_seconds:24,sample_fps:15,attempt_timeout:120,deadline_seconds:300}})).json();
 const tid=created.id;
 await waitFor(async()=>{const d=await get('/api/tasks/'+tid);return d.attempts.some(a=>a.status==='RUNNING');},60);
 process.kill(pids['worker-1'],'SIGSTOP');paused=true;
 let lost=await waitFor(async()=>{const r=await get('/api/node-incidents?task_id='+tid);return r.some(x=>x.affected_segments>0)?r:null;},60);
 expect(lost[0].affected[0].last_status).toBe('RUNNING');
 expect(lost[0].link_restored_at).toBeNull();
 save('失联时记录.json',lost);
 await page.goto(base+'/?page=incidents');
 await expect(page.locator('.incident-record').first()).toContainText(tid);
 await shot('27-失联影响',page.locator('.weekly'));
 process.kill(pids['worker-1'],'SIGCONT');paused=false;
 const recovered=await waitFor(async()=>{const r=await get('/api/node-incidents?task_id='+tid);return r[0]?.task_reconciled_at?r:null;},80);
 expect(recovered[0].task_reconciled_at).toBeGreaterThanOrEqual(recovered[0].link_restored_at);
 const final=await waitFor(async()=>{const t=await get('/api/tasks/'+tid);if(['FAILED','TIMED_OUT'].includes(t.status))throw Error(t.error);return t.status==='SUCCEEDED'?t:null;},120);
 const finalEvents=await get('/api/tasks/'+tid+'/events');
 expect(finalEvents.filter(e=>e.type==='node_lost')).toHaveLength(1);
 expect(final.attempts).toHaveLength(1);
 expect(final.result.sampled_frames).toBe(240);
 save('失联恢复任务.json',{...final,events:finalEvents,incidents:await get('/api/node-incidents?task_id='+tid),injection:{method:'SIGSTOP/SIGCONT',node_id:'lab-1',environment:'isolated server_process'}});
 await page.reload();await expect(page.locator('.incident-record').first()).toContainText('已完成');
 await shot('27-恢复核对',page.locator('.weekly'));
 console.log('loss and recovery passed',tid);
}catch(e){await page.screenshot({path:out+'/failure.png',fullPage:true});throw e;}
finally{if(paused)process.kill(pids['worker-1'],'SIGCONT');}
expect(errors).toEqual([]);
save('验证汇总.json',{date:'2026-11-04',environment:'独立管理服务和4个服务器进程执行器',checks:{candidate_filter:true,label_exclusion:true,upload:true,source_playback:true,tail_playback:true,split_durations:[7,7,7,3],dispatch_requests:4,dispatch_acknowledgements:4,normal_frames:48,loss_incident_deduplicated:true,recovery_same_attempt:true,recovery_frames:240},browser_errors:errors});
await browser.close();
console.log('ALL LIVE CHECKS PASSED');
